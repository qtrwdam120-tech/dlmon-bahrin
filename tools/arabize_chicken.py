def main():
    with open("firestore-import-result.json", encoding="utf-8") as f:
        created = json.load(f)["createdIds"]
    if len(created) != len(TRANSLATIONS):
        raise SystemExit(f"count mismatch: {len(created)} ids vs {len(TRANSLATIONS)} translations")

    email, password, api_key = panel_credentials()
    token = sign_in(api_key, email, password)
    docs = firestore_get(f"{BASE}/products?pageSize=400", token).get("documents", [])
    chicken_ids = set(created)

    # المنتجات الجديدة في الأعلى: الدجاج أولاً بترتيب المصدر، ثم بقية المنتجات بترتيبها الحالي
    rest = sorted(
        ((int(d["fields"].get("order", {}).get("integerValue", 0)), d["name"].rsplit("/", 1)[-1])
         for d in docs if d["name"].rsplit("/", 1)[-1] not in chicken_ids),
    )
    new_order = {doc_id: i for i, doc_id in enumerate(created)}
    for offset, (_, doc_id) in enumerate(rest, start=len(created)):
        new_order[doc_id] = offset

    for doc_id, (name, desc) in zip(created, TRANSLATIONS):
        update_doc(doc_id, {"name": name, "desc": desc, "order": new_order[doc_id]}, token)

    for _, doc_id in rest:
        update_doc(doc_id, {"order": new_order[doc_id]}, token)

    print(f"arabized {len(TRANSLATIONS)} chicken products and moved them to the top")
    print(f"original products shifted to orders {len(created)}–{len(created) + len(rest) - 1}")


if __name__ == "__main__":
    main()
